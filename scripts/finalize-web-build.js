/**
 * Post-export cleanup for the web build.
 *
 * Expo's static export leaves three things that actively hurt crawling:
 *  1. Dynamic routes only exist as files for the params known at build time,
 *     so any listing created after the last deploy 404s for users and Google.
 *  2. The dynamic route templates themselves ship as crawlable URLs
 *     (/vehicle/[id], /category/[slug]) alongside URL-encoded twins.
 *  3. Private / duplicate routes (auth, settings, messages, the Expo dev
 *     sitemap) are indexable and near-identical to each other.
 *
 * This script rewrites those so only real content pages stay indexable.
 */
const fs = require('fs/promises');
const path = require('path');
const { toUrlSlug, isRouteTemplate } = require('./seo-utils');

const DIST_DIR = path.join(process.cwd(), 'dist');

// Dynamic route shells: copied to a bracket-free name so Netlify can rewrite
// unknown children onto them without URL-encoding ambiguity in _redirects.
const DYNAMIC_SHELLS = [
  { source: 'vehicle/[id].html', fallback: 'vehicle/_shell.html', prefix: '/vehicle/*' },
  { source: 'category/[slug].html', fallback: 'category/_shell.html', prefix: '/category/*' },
];

// Routes that must never be indexed: private surfaces, auth funnels, framework
// artifacts, and the raw dynamic templates (duplicates of real content pages).
const NOINDEX_PATTERNS = [
  /^_sitemap\.html$/,
  /^%2Bhtml\.html$/,
  /^\+not-found\.html$/,
  /^modal\.html$/,
  /^auth\//,
  /^settings\//,
  /^messages\//,
  /^notifications\//,
  /^verify\//,
  /^history\//,
  /^listings\//,
  /^order\//,
  /^favorites\.html$/,
  /^profile\.html$/,
  // Gated listing form — prerenders to an empty shell, so indexing it just
  // feeds Google a thin page.
  /^sell\.html$/,
  /^\(tabs\)\//,
  /^vehicle\/edit\.html$/,
  /^delete\//,
  /^report\//,
  // Dynamic templates and their URL-encoded twins.
  /(\[|%5B)/i,
  /_shell\.html$/,
];

const NOINDEX_TAG = '<meta name="robots" content="noindex, follow"/>';

async function listHtmlFiles(dir) {
  const out = [];
  const entries = await fs.readdir(dir, { withFileTypes: true });

  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === '_expo' || entry.name === 'assets') continue;
      out.push(...(await listHtmlFiles(full)));
    } else if (entry.name.endsWith('.html')) {
      out.push(full);
    }
  }

  return out;
}

function toRelativeRoute(fullPath) {
  return path.relative(DIST_DIR, fullPath).split(path.sep).join('/');
}

/**
 * Categories export as "category/Petrol Car.html". That serves at
 * /category/Petrol Car — a URL containing a literal space, which is not
 * fetchable and which Netlify additionally lowercases, so the submitted URL
 * 301'd at best. Republish each one under a kebab slug and redirect the old
 * shapes at it, so exactly one fetchable URL exists per category.
 */
async function normalizeCategoryUrls() {
  const categoryDir = path.join(DIST_DIR, 'category');
  const rules = [];

  let entries;
  try {
    entries = await fs.readdir(categoryDir, { withFileTypes: true });
  } catch {
    return rules;
  }

  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith('.html')) continue;

    const name = entry.name.slice(0, -'.html'.length);
    if (isRouteTemplate(name)) continue;

    const slug = toUrlSlug(name);
    if (!slug || slug === name) continue;

    await fs.rename(path.join(categoryDir, name + '.html'), path.join(categoryDir, slug + '.html'));

    // Netlify lowercases the path before matching, so the rule only has to
    // cover the lowercase encoded form the old URL collapses to. When that
    // already equals the slug ("Motorcycle" -> "motorcycle") a rule would be a
    // self-redirect, which Netlify serves as an infinite loop.
    const legacy = encodeURI(name.toLowerCase());
    if (legacy !== slug) {
      rules.push(`/category/${legacy}  /category/${slug}  301!`);
    }
    console.log(`  category: ${name} -> ${slug}`);
  }

  return rules;
}

async function copyDynamicShells() {
  const rules = [];

  for (const shell of DYNAMIC_SHELLS) {
    const source = path.join(DIST_DIR, shell.source);
    try {
      await fs.copyFile(source, path.join(DIST_DIR, shell.fallback));
      rules.push(`${shell.prefix}  /${shell.fallback}  200`);
    } catch {
      console.warn(`  ! missing dynamic shell, skipping fallback: ${shell.source}`);
    }
  }

  return rules;
}

async function writeRedirects(rules) {
  const body = [
    '# Generated by scripts/finalize-web-build.js — do not edit by hand.',
    '# Static files win over these rules, so prerendered pages are unaffected.',
    '# Unknown dynamic children fall back to the client-rendered shell instead',
    '# of 404ing, which is what happens to any listing created since the last build.',
    ...rules,
    '',
  ].join('\n');

  await fs.writeFile(path.join(DIST_DIR, '_redirects'), body, 'utf8');
  console.log(`  _redirects written (${rules.length} rules)`);
}

function applyNoindex(html) {
  // Drop any indexable robots directive the SEO injector added, then force noindex.
  const stripped = html.replace(/<meta\s+name="robots"[^>]*\/?>/gi, '');
  return stripped.replace(/<head>/i, `<head>${NOINDEX_TAG}`);
}

async function noindexJunkRoutes(files) {
  let count = 0;

  for (const fullPath of files) {
    const route = toRelativeRoute(fullPath);
    if (!NOINDEX_PATTERNS.some((pattern) => pattern.test(route))) continue;

    const html = await fs.readFile(fullPath, 'utf8');
    if (!/<head>/i.test(html)) continue;

    const next = applyNoindex(html);
    if (next !== html) {
      await fs.writeFile(fullPath, next, 'utf8');
      count += 1;
    }
  }

  console.log(`  noindex applied to ${count} non-content routes`);
}

async function finalize() {
  console.log('Finalizing web build for crawlers...');
  // Category 301s must precede the /category/* shell fallback: _redirects is
  // first-match-wins, and the wildcard would otherwise swallow them.
  const categoryRules = await normalizeCategoryUrls();
  const shellRules = await copyDynamicShells();
  await writeRedirects([...categoryRules, ...shellRules]);

  const files = await listHtmlFiles(DIST_DIR);
  await noindexJunkRoutes(files);
  console.log(`Done. ${files.length} HTML files in dist.`);
}

finalize().catch((error) => {
  console.error('Failed to finalize web build:', error);
  process.exit(1);
});
